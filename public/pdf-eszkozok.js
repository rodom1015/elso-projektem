// A beépített betűkészlet (Helvetica) nem ismer minden ékezetet (pl. ő, č) – ezeket a legközelebbire cseréljük
function pdfBiztonsagosSzoveg(betu, s) {
  return [...s].map((ch) => {
    try { betu.encodeText(ch); return ch; }
    catch {
      const csere = { "ő": "ö", "ű": "ü", "Ő": "Ö", "Ű": "Ü" }[ch] ?? ch.normalize("NFD").replace(/[̀-ͯ]/g, "");
      try { betu.encodeText(csere); return csere; } catch { return "?"; }
    }
  }).join("");
}

async function pdfFuttat() {
  if (!pdfBemenet.length) return ertesit(t("pdf_err_need"), true);
  await pdfLibBetolt();
  const { PDFDocument, degrees, rgb, StandardFonts } = PDFLib;
  const gomb = $("pdf-futtat");
  gomb.disabled = true;
  gomb.textContent = t("pdf_working");
  try {
    let ki = null, nev = "", reszek = null;
    const elso = pdfBemenet[0];
    const alap = (elso.nev || "dokumentum").replace(/\.[^.]+$/, "");
    if (pdfFul === "egyesit") {
      ki = await PDFDocument.create();
      for (const f of pdfBemenet) {
        const forras = await PDFDocument.load(f.bajtok);
        (await ki.copyPages(forras, forras.getPageIndices())).forEach((o) => ki.addPage(o));
      }
      nev = alap + "_egyesitett.pdf";
    } else if (pdfFul === "kivon") {
      const forras = await PDFDocument.load(elso.bajtok);
      const lista = oldalLista($("pdf-oldalak").value, forras.getPageCount());
      if ($("pdf-kulon").checked) {
        reszek = [];
        for (const i of lista) {
          const d = await PDFDocument.create();
          const [o] = await d.copyPages(forras, [i]);
          d.addPage(o);
          reszek.push({ nev: `${alap}_${String(i + 1).padStart(3, "0")}.pdf`, bajtok: await d.save() });
        }
      } else {
        ki = await PDFDocument.create();
        (await ki.copyPages(forras, lista)).forEach((o) => ki.addPage(o));
        nev = alap + "_oldalak.pdf";
      }
    } else if (pdfFul === "forgat") {
      ki = await PDFDocument.load(elso.bajtok);
      const szog = +$("pdf-szog").value;
      for (const i of oldalLista($("pdf-oldalak").value, ki.getPageCount())) {
        const o = ki.getPage(i);
        o.setRotation(degrees((o.getRotation().angle + szog) % 360));
      }
      nev = alap + "_forgatott.pdf";
    } else if (pdfFul === "torol") {
      ki = await PDFDocument.load(elso.bajtok);
      const torlendo = [...new Set(oldalLista($("pdf-oldalak").value, ki.getPageCount()))].sort((a, b) => b - a);
      if (!$("pdf-oldalak").value.trim() || torlendo.length >= ki.getPageCount()) throw new Error(t("pdf_err_all"));
      torlendo.forEach((i) => ki.removePage(i));
      nev = alap + "_javitott.pdf";
    } else if (pdfFul === "kepek") {
      ki = await PDFDocument.create();
      const a4 = $("pdf-meret").value === "a4";
      for (const f of pdfBemenet) {
        const kep = f.tipus === "image/png" ? await ki.embedPng(f.bajtok) : await ki.embedJpg(f.bajtok);
        if (a4) {
          const fekvo = kep.width > kep.height;
          const [W, H] = fekvo ? [841.89, 595.28] : [595.28, 841.89];
          const margo = 28, arany = Math.min((W - 2 * margo) / kep.width, (H - 2 * margo) / kep.height, 1);
          const w = kep.width * arany, h = kep.height * arany;
          ki.addPage([W, H]).drawImage(kep, { x: (W - w) / 2, y: (H - h) / 2, width: w, height: h });
        } else {
          ki.addPage([kep.width, kep.height]).drawImage(kep, { x: 0, y: 0, width: kep.width, height: kep.height });
        }
      }
      nev = alap + ".pdf";
    } else if (pdfFul === "szamoz") {
      ki = await PDFDocument.load(elso.bajtok);
      const betu = await ki.embedFont(StandardFonts.Helvetica);
      const oldalak = ki.getPages(), osszes = oldalak.length;
      const kezdo = parseInt($("pdf-kezdo").value, 10) || 1, forma = $("pdf-forma").value, hely = $("pdf-hely").value;
      const kijelolt = new Set(oldalLista($("pdf-oldalak").value, osszes));
      oldalak.forEach((o, i) => {
        if (!kijelolt.has(i)) return;
        const szoveg = forma.replace("{n}", String(kezdo + i)).replace("{o}", String(kezdo + osszes - 1));
        const { width, height } = o.getSize(), meretPt = 10, w = betu.widthOfTextAtSize(szoveg, meretPt);
        const x = hely === "bc" ? (width - w) / 2 : width - w - 36, y = hely === "tr" ? height - 30 : 22;
        o.drawText(szoveg, { x, y, size: meretPt, font: betu, color: rgb(0.25, 0.25, 0.25) });
      });
      nev = alap + "_szamozott.pdf";
    } else if (pdfFul === "vizjel") {
      ki = await PDFDocument.load(elso.bajtok);
      const betu = await ki.embedFont(StandardFonts.HelveticaBold);
      const szoveg = pdfBiztonsagosSzoveg(betu, $("pdf-szoveg").value.trim() || t("pdf_text_def"));
      const meretPt = +$("pdf-betu").value, atlatszo = +$("pdf-atlatszo").value;
      for (const o of ki.getPages()) {
        const { width, height } = o.getSize();
        const w = betu.widthOfTextAtSize(szoveg, meretPt), szog = Math.atan2(height, width);
        const x = width / 2 - (w / 2) * Math.cos(szog) + (meretPt / 3) * Math.sin(szog);
        const y = height / 2 - (w / 2) * Math.sin(szog) - (meretPt / 3) * Math.cos(szog);
        o.drawText(szoveg, { x, y, size: meretPt, font: betu, color: rgb(0.8, 0.1, 0.1), opacity: atlatszo, rotate: degrees((szog * 180) / Math.PI) });
      }
      nev = alap + "_vizjeles.pdf";
    }
    if (reszek) pdfEredmeny = { reszek };
    else pdfEredmeny = { nev, bajtok: await ki.save(), oldalak: ki.getPageCount() };
    pdfKimenetRajzol();
    esemenyKuld("masol", "PDF " + pdfFul);
  } catch (hiba) {
    ertesit(/encrypt/i.test(String(hiba.message)) ? t("pdf_err_encrypted") : hiba.message, true);
  } finally {
    gomb.disabled = false;
    gomb.textContent = t("pdf_run");
  }
}

