async function pdfHozzaad(fajlLista) {
  const kep = pdfFul === "kepek", tobb = pdfFul === "egyesit" || kep;
  if (!tobb) pdfBemenet = [];
  for (const f of fajlLista) {
    try {
      const bajtok = f.bajtok || new Uint8Array(await f.arrayBuffer());
      if (kep) pdfBemenet.push({ nev: f.name || f.nev, bajtok, tipus: f.type || (/\.png$/i.test(f.nev) ? "image/png" : "image/jpeg") });
      else pdfBemenet.push(await pdfBetolt(bajtok, f.name || f.nev));
    } catch (hiba) { ertesit(hiba.message, true); }
  }
  pdfEredmeny = null;
  $("pdf-kimenet").hidden = true;
  pdfListaRajzol();
}

