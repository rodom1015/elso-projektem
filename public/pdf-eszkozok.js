// "1-3, 5, 8-" → [0,1,2,4,7,8,...] (0-tól számozva); üres → mind
function oldalLista(szoveg, n) {
  const s = szoveg.replace(/\s/g, "");
  if (!s) return [...Array(n).keys()];
  const ki = [];
  for (const resz of s.split(/[,;]/).filter(Boolean)) {
    const m = resz.match(/^(\d+)?(-)?(\d+)?$/);
    if (!m || (!m[1] && !m[3])) throw new Error(t("pdf_err_pages", { p: resz, n }));
    const a = m[1] ? +m[1] : 1, b = m[2] ? (m[3] ? +m[3] : n) : a;
    if (a < 1 || b > n || a > b) throw new Error(t("pdf_err_pages", { p: resz, n }));
    for (let i = a; i <= b; i++) ki.push(i - 1);
  }
  return ki;
}

async function pdfBetolt(bajtok, nev) {
  await pdfLibBetolt();
  try {
    const doc = await PDFLib.PDFDocument.load(bajtok, { updateMetadata: false });
    return { nev, bajtok, oldalak: doc.getPageCount() };
  } catch (e) {
    throw new Error(/encrypt/i.test(String(e && e.message)) ? t("pdf_err_encrypted") : t("pdf_err_read", { n: nev }));
  }
}

